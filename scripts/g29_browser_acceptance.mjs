import { chromium } from 'playwright';

const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
let page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const base = 'https://workledger-enterprise.vercel.app/ui/app/index.html';
const checks = [];
const body = () => page.locator('body').innerText();
async function open(route, role) {
  console.log('open', route);
  await page.close();
  page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  await page.goto(`${base}#${route}`, { waitUntil: 'domcontentloaded', timeout: 15000 });
  await page.waitForTimeout(600);
  await page.locator('select.role').selectOption(role);
  await page.waitForTimeout(400);
}
await open('projects', 'project-director');
console.log('projects loaded');
await page.locator('[data-workflow="open-provenance"]').click({ timeout: 5000 });
checks.push(['evidence provenance', (await body()).includes('Provenance lineage opened') && (await page.locator('#drawer').count()) === 1]);
await page.screenshot({ path: 'evidence/g29-evidence-provenance.png', fullPage: true });
await open('diary', 'site-manager');
console.log('diary loaded');
console.log('diary action count', await page.locator('[data-workflow="acknowledge-diary"]').count(), (await body()).slice(0,120));
await page.locator('[data-workflow="acknowledge-diary"]').click({ timeout: 5000 });
checks.push(['diary acknowledgement', (await body()).includes('Diary D-2026-1112 acknowledged')]);
await page.screenshot({ path: 'evidence/g29-diary-acknowledged.png', fullPage: true });
await open('progress', 'independent-reviewer');
console.log('progress loaded');
await page.locator('[data-workflow="open-review"]').click({ timeout: 5000 });
await page.locator('[data-workflow="complete-review"]').click({ timeout: 5000 });
checks.push(['review completion', (await body()).includes('independently verified')]);
await page.screenshot({ path: 'evidence/g29-review-completed.png', fullPage: true });
await open('audit', 'contract-admin');
console.log('audit loaded');
await page.locator('[data-workflow="filter-audit"]').click({ timeout: 5000 });
checks.push(['audit filter', (await body()).includes('Audit view filtered to verified records')]);
await page.screenshot({ path: 'evidence/g29-audit-filtered.png', fullPage: true });
console.log(JSON.stringify({ deployment: page.url(), checks }, null, 2));
if (checks.some(([, ok]) => !ok)) process.exitCode = 1;
await browser.close();
